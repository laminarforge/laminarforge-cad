// Closed module latch-force and alignment verification station.
//
// Intent:
// - Dock a sealed chip cassette or module against repeatable datums before it
//   enters the incubator/workcell flow.
// - Provide a gauge pocket for latch force, alignment pin gauge blocks,
//   cassette/module datum nest, insertion-depth hard stop, witness marks,
//   fiducials, barcode/certificate lands, release/hold/reject lanes, reject
//   quarantine pocket, robot keepouts, and a rear service bulkhead.
//
// This is interface and packaging CAD only. It is not a latch design, force
// calibration procedure, sterile barrier claim, or metrology certification.

// Stable STL outputs generated by this binary:
