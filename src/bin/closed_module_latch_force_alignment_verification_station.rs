fn datum_pins() -> Part {
    let mut pins = Part::empty("closed_module_latch_alignment_datum_pins");
    for (index, (x, y)) in datum_pin_points().iter().enumerate() {
        let boss = centered_cylinder(
            format!("closed_module_latch_alignment_datum_pin_boss_{index}"),
            DATUM_PIN_BOSS_D / 2.0,
            10.0,
            36,
        )
        .translate(*x, *y, DATUM_NEST_Z / 2.0 + 5.0);
        let pilot = centered_cylinder(
            format!("closed_module_latch_alignment_precision_pin_{index}"),
            DATUM_PIN_D / 2.0,
            18.0,
            32,
        )
        .translate(*x, *y, DATUM_NEST_Z / 2.0 + 12.0);
        pins = pins + boss + pilot;
    }
    pins
}

fn latch_reference_pads() -> Part {
    let mut pads = Part::empty("closed_module_latch_alignment_latch_reference_pads");
    for (index, x) in [
        -MODULE_X * 0.34,
        -MODULE_X * 0.12,
        MODULE_X * 0.12,
        MODULE_X * 0.34,
    ]
    .iter()
    .enumerate()
    {
        let pad = centered_cube(
            format!("closed_module_latch_alignment_latch_reference_pad_{index}"),
            52.0,
            18.0,
            8.0,
        )
        .translate(*x, -(MODULE_Y / 2.0 + 22.0), DATUM_NEST_Z / 2.0 + 4.0);
        let witness_slot = centered_cube(
            format!("closed_module_latch_alignment_latch_witness_slot_{index}"),
            24.0,
            4.0,
            9.0,
        )
        .translate(*x, -(MODULE_Y / 2.0 + 22.0), DATUM_NEST_Z / 2.0 + 5.0);
        pads = pads + (pad - witness_slot);
    }
    pads
}

