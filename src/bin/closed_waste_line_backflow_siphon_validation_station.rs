fn tube_clip_comb() -> Part {
    let mut comb = Part::empty("waste_line_tube_clip_comb");
    for i in 0..TUBE_CLIPS {
        let x = lane_x(i, TUBE_CLIPS, 40.0);
        let clip = centered_cube(
            format!("waste_line_closed_tube_clip_body_{i}"),
            24.0,
            44.0,
            32.0,
        )
        .translate(x, -BAG_NEST_Y / 2.0 - 28.0, 18.0);
        let bore = centered_cylinder(
            format!("waste_line_closed_tube_clip_bore_{i}"),
            TUBE_BORE_D / 2.0,
            32.0,
            20,
        )
        .rotate(90.0, 0.0, 0.0)
        .translate(x, -BAG_NEST_Y / 2.0 - 28.0, 18.0);
        let split = centered_cube(
            format!("waste_line_tube_clip_snap_gap_{i}"),
            8.0,
            46.0,
            18.0,
        )
        .translate(x, -BAG_NEST_Y / 2.0 - 28.0, 34.0);
        comb = comb + (clip - bore - split);
    }
    comb
}

