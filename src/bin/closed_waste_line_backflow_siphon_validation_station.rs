// Closed waste-line backflow/siphon validation station for automated sterile
// cell-culture modules.
//
// Practical scope:
// - Holds a disposable/closed waste bag and waste tube harness without opening
//   the fluid path.
// - Challenges check valves and siphon paths using bought-in pressure/vacuum
//   sources, gauges, sterile connectors, dye tracer capsules, and sensors.
// - Provides explicit release/hold/reject disposition, barcode custody lands,
//   used/clean segregation, drip containment, and robot/service clearances.
//
// Stable STL outputs generated by this binary:
// - output/closed_waste_line_backflow_siphon_validation_station_leak_tray_base.stl
// - output/closed_waste_line_backflow_siphon_validation_station_waste_bag_tube_nest.stl
// - output/closed_waste_line_backflow_siphon_validation_station_check_valve_challenge_fixture.stl
// - output/closed_waste_line_backflow_siphon_validation_station_vertical_head_siphon_reference_column.stl
// - output/closed_waste_line_backflow_siphon_validation_station_pressure_vacuum_witness_ports.stl
// - output/closed_waste_line_backflow_siphon_validation_station_dye_tracer_recovery_nests.stl
// - output/closed_waste_line_backflow_siphon_validation_station_barcode_custody_lands.stl
// - output/closed_waste_line_backflow_siphon_validation_station_release_hold_reject_lanes.stl
// - output/closed_waste_line_backflow_siphon_validation_station_clean_used_segregation.stl
// - output/closed_waste_line_backflow_siphon_validation_station_closed_route_guard_comb.stl
// - output/closed_waste_line_backflow_siphon_validation_station_robot_service_keepouts.stl
// - output/closed_waste_line_backflow_siphon_validation_station_assembly.stl
//
// This is product-concept packaging CAD for validation hardware. It does not
// define sterile processing, biohazard treatment, check-valve acceptance
// criteria, or pressure/vacuum operating limits.

