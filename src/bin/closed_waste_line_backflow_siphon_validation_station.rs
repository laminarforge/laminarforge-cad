fn leak_tray_base() -> Part {
    let deck = centered_cube(
        "waste_line_backflow_base_deck",
        STATION_X,
        STATION_Y,
        BASE_Z,
    )
    .translate(0.0, 0.0, BASE_Z / 2.0);
    let leak_basin = centered_cube(
        "waste_line_backflow_leak_basin_recess",
        LEAK_BASIN_X,
        LEAK_BASIN_Y,
        LEAK_BASIN_DEPTH,
    )
    .translate(0.0, 0.0, BASE_Z - LEAK_BASIN_DEPTH / 2.0);
    let drain = centered_cylinder(
        "waste_line_backflow_leak_tray_front_drain",
        DRAIN_PORT_D / 2.0,
        54.0,
        36,
    )
    .rotate(90.0, 0.0, 0.0)
    .translate(
        STATION_X / 2.0 - 98.0,
        -STATION_Y / 2.0 + 26.0,
        BASE_Z - 10.0,
    );

    deck - leak_basin - drain - mount_holes()
        + perimeter_rim()
        + leak_sensor_wells()
        + drip_flow_ribs()
        + datum_fiducials()
        + station_zone_lands()
}

fn perimeter_rim() -> Part {
    let front = centered_cube("waste_line_front_leak_rim", STATION_X, RIM_W, RIM_Z).translate(
        0.0,
        -STATION_Y / 2.0 + RIM_W / 2.0,
        BASE_Z + RIM_Z / 2.0,
    );
    let rear = centered_cube("waste_line_rear_leak_rim", STATION_X, RIM_W, RIM_Z).translate(
        0.0,
        STATION_Y / 2.0 - RIM_W / 2.0,
        BASE_Z + RIM_Z / 2.0,
    );
    let left = centered_cube("waste_line_left_leak_rim", RIM_W, STATION_Y, RIM_Z).translate(
        -STATION_X / 2.0 + RIM_W / 2.0,
        0.0,
        BASE_Z + RIM_Z / 2.0,
    );
    let right = centered_cube("waste_line_right_leak_rim", RIM_W, STATION_Y, RIM_Z).translate(
        STATION_X / 2.0 - RIM_W / 2.0,
        0.0,
        BASE_Z + RIM_Z / 2.0,
    );
    front + rear + left + right
}

fn mount_holes() -> Part {
    let mut holes = Part::empty("waste_line_mount_holes");
    for (i, (x, y)) in [
        (-STATION_X / 2.0 + 54.0, -STATION_Y / 2.0 + 54.0),
        (STATION_X / 2.0 - 54.0, -STATION_Y / 2.0 + 54.0),
        (-STATION_X / 2.0 + 54.0, STATION_Y / 2.0 - 54.0),
        (STATION_X / 2.0 - 54.0, STATION_Y / 2.0 - 54.0),
        (0.0, -STATION_Y / 2.0 + 54.0),
        (0.0, STATION_Y / 2.0 - 54.0),
    ]
    .iter()
    .enumerate()
    {
        holes = holes
            + centered_cylinder(
                format!("waste_line_m6_mount_clearance_{i}"),
                MOUNT_HOLE_D / 2.0,
                BASE_Z + 6.0,
                28,
            )
            .translate(*x, *y, BASE_Z / 2.0);
    }
    holes
}

